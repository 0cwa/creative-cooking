import fs from 'node:fs';
import path from 'node:path';

const inputPath = process.argv[2] ?? 'artifacts/loro/web-native-input.json';
const outputPath = process.argv[3] ?? 'scripts/spikes/loro/native-fixture.ts';
const input = JSON.parse(fs.readFileSync(inputPath, 'utf8'));

function bytesFromBase64(value) {
  return Array.from(Buffer.from(value, 'base64'));
}

const source = `// Generated by materialize-native-fixture.mjs. Do not edit.
export const webPackage = ${JSON.stringify(input.webPackage)};
export const scenario = ${JSON.stringify(input.scenario)};
export const baseSnapshot = Uint8Array.from(${JSON.stringify(bytesFromBase64(input.snapshotBase64))}).buffer;
export const webUpdate = Uint8Array.from(${JSON.stringify(bytesFromBase64(input.webUpdateBase64))}).buffer;
export const expectedBase = ${JSON.stringify(input.baseJson, null, 2)} as const;
export const expectedWebFork = ${JSON.stringify(input.webForkJson, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, source);
console.log(JSON.stringify({ inputPath, outputPath, snapshotBytes: bytesFromBase64(input.snapshotBase64).length, updateBytes: bytesFromBase64(input.webUpdateBase64).length }));

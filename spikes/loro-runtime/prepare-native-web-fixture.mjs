import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LoroDoc } from 'loro-crdt';
import { seed } from './engine.shared.ts';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));

export function createNativeWebFixture() {
  const baseSnapshot = seed(LoroDoc);
  const web = new LoroDoc();
  web.import(baseSnapshot);
  web.setPeerId('202');
  const baseVersion = web.oplogVersion();
  web.getMap('recipe').set('title', 'Lentil soup (B) 🍲');
  web.getMap('ingredient:ing-stock-8').set('amount', '900 ml');
  web.getList('step-order').delete(1, 1);
  web.getList('step-order').insert(1, 'step-simmer-25m-3');
  web.getMap('step:step-simmer-25m-3').set('id', 'step-simmer-25m-3');
  web.getMap('step:step-simmer-25m-3').set('text', 'Simmer for 25 minutes — 🍲');

  return {
    baseSnapshot,
    update: web.export({ mode: 'update', from: baseVersion }),
  };
}

const fixture = createNativeWebFixture();
const generated = `// Generated by prepare-native-web-fixture.mjs from loro-crdt 1.17.1.
// This payload is imported by the Hermes fixture through loro-react-native 1.10.3.
export const NATIVE_WEB_BASE_SNAPSHOT = Uint8Array.from(${JSON.stringify(Array.from(fixture.baseSnapshot))});
export const NATIVE_WEB_UPDATE = Uint8Array.from(${JSON.stringify(Array.from(fixture.update))});
`;

await writeFile(path.join(scriptDirectory, 'native-web-fixture.ts'), generated);
console.log(JSON.stringify({
  webSdk: 'loro-crdt 1.17.1',
  baseSnapshotBytes: fixture.baseSnapshot.byteLength,
  webUpdateBytes: fixture.update.byteLength,
  output: 'spikes/loro-runtime/native-web-fixture.ts',
}, null, 2));
